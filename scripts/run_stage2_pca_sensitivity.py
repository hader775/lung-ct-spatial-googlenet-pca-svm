#!/usr/bin/env python3
"""New evidence only: whole-image baseline, patch PCA sensitivity, multi-seed random baseline.
Inputs MUST include matched 64-patch frozen GoogLeNet features, label & group arrays,
audit file and SHA-indexed manifest generated from the same original images.
No medical results are generated by this code until it is run on actual features.
"""
import os
os.environ.setdefault('OPENBLAS_NUM_THREADS','3')
os.environ.setdefault('OMP_NUM_THREADS','3')
import json, csv, zipfile, hashlib, argparse, pathlib
from collections import Counter
import numpy as np
from sklearn.decomposition import PCA
from sklearn.model_selection import StratifiedGroupKFold
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC
from sklearn.metrics import accuracy_score, f1_score, recall_score, balanced_accuracy_score

CLASSES=['Benign','Malignant','Normal']

def sha_file(path,block=1<<20):
 h=hashlib.sha256()
 with open(path,'rb') as f:
  for b in iter(lambda:f.read(block),b''):
   h.update(b)
 return h.hexdigest()

def load_manifest(p):
 with open(p, encoding='utf-8-sig',newline='') as f: r=list(csv.DictReader(f))
 assert [int(x['index']) for x in r]==list(range(len(r))), 'Manifest rows must be in original feature-cache order'
 return r

def load_whole_features(args,manifest):
 out=pathlib.Path(args.out);out.mkdir(parents=True,exist_ok=True)
 cache=out/'whole_image_googlenet_1024.npy'
 if cache.exists():
  X=np.load(cache,mmap_mode='r');assert X.shape==(len(manifest),1024)
  print('Using saved whole-image cache:',cache,flush=True)
  return X
 if not args.dataset or not args.weights:
  print('Whole-image baseline SKIPPED: provide --dataset and --weights to extract it.',flush=True)
  return None
 import cv2, torch
 from torchvision.models import googlenet
 from numpy.lib.format import open_memmap
 weights_sha=sha_file(args.weights)
 if not weights_sha.startswith('1378be20'):
  raise ValueError('The checkpoint does not match official torchvision GoogLeNet weights. Refusing to use it.')
 model=googlenet(weights=None,aux_logits=True,transform_input=False,init_weights=False)
 model.load_state_dict(torch.load(args.weights,map_location='cpu',weights_only=True), strict=True)
 model.aux1=None;model.aux2=None;model.aux_logits=False
 model.fc=torch.nn.Identity();model.transform_input=True;model.eval()
 device=torch.device('cuda' if torch.cuda.is_available() else 'cpu');model.to(device)
 print('Extracting whole-image deep features on',device,flush=True)
 mean=torch.tensor([.485,.456,.406],device=device).view(1,3,1,1)
 std=torch.tensor([.229,.224,.225],device=device).view(1,3,1,1)
 data=pathlib.Path(args.dataset)
 if data.is_file() and data.suffix.lower()=='.zip':
  with zipfile.ZipFile(data) as z:
   img_bytes={hashlib.sha256(z.read(k)).hexdigest():z.read(k) for k in z.namelist() if k.lower().endswith(('.jpg','.jpeg','.png'))}
 elif data.is_dir():
  files=[p for p in data.rglob('*') if p.suffix.lower() in ('.jpg','.jpeg','.png')]
  img_bytes={hashlib.sha256(b).hexdigest():b for p in files for b in [p.read_bytes()]}
 else: raise ValueError('Provide folder or ZIP as --dataset')
 missing=[r['sha256'] for r in manifest if r['sha256'] not in img_bytes]
 if missing: raise ValueError(f'Missing {len(missing)} manifest images from dataset; do not align features by position without SHA checking.')
 tmp=cache.with_suffix('.partial.npy');X=open_memmap(tmp,mode='w+',dtype='float32',shape=(len(manifest),1024))
 bs=16
 for i in range(0,len(manifest),bs):
  ims=[]
  for r in manifest[i:i+bs]:
   im=cv2.imdecode(np.frombuffer(img_bytes[r['sha256']],dtype='uint8'),cv2.IMREAD_GRAYSCALE)
   if im is None: raise RuntimeError('Cannot decode '+r['file'])
   im=cv2.resize(im,(224,224),interpolation=cv2.INTER_AREA)
   ims.append(im)
  tens=torch.from_numpy(np.stack(ims).astype('float32')[:,None]/255.).repeat(1,3,1,1).to(device)
  tens=(tens-mean)/std
  with torch.inference_mode():feat=model(tens).detach().cpu().numpy()
  X[i:i+len(ims)]=feat
  if (i//bs)%10==0:print('Whole-image features:',i+len(ims),'/',len(manifest),flush=True)
 X.flush();del X
 os.replace(tmp,cache)
 return np.load(cache,mmap_mode='r')

def svc_predict(tr,te,yt):
 clf=make_pipeline(StandardScaler(),SVC(C=1.0,kernel='rbf',gamma='scale',class_weight='balanced'))
 clf.fit(tr,yt)
 return clf.predict(te)

def metrics(y,p):
 return dict(accuracy_pct=100*accuracy_score(y,p),macro_f1_pct=100*f1_score(y,p,average='macro',labels=[0,1,2],zero_division=0),
   balanced_accuracy_pct=100*balanced_accuracy_score(y,p), benign_recall_pct=100*recall_score(y,p,labels=[0],average='macro',zero_division=0))

def evaluate(args):
 out=pathlib.Path(args.out);out.mkdir(exist_ok=True,parents=True)
 root=pathlib.Path(args.cache)
 Z=np.load(root/'features_64_224.npy',mmap_mode='r')
 Y=np.load(root/'labels.npy');GR=np.load(root/'groups.npy')
 manifest=load_manifest(args.manifest)
 if Z.shape!=(len(Y),64,1024) or len(manifest)!=len(Y):
  raise ValueError(f'Cache shape {Z.shape}, y {len(Y)}, manifest {len(manifest)} mismatch')
 ym=np.array([int(r['label_code']) for r in manifest]);gm=np.array([int(r['similarity_group']) for r in manifest])
 if not np.array_equal(Y,ym) or not np.array_equal(GR,gm):
  raise ValueError('Feature cache does not match supplied manifest label/group order')
 if (root/'audit.json').exists():
  audit=json.loads((root/'audit.json').read_text())
  if audit.get('pretrained_sha256') and args.weights:
   if audit['pretrained_sha256']!=sha_file(args.weights): raise ValueError('GoogLeNet checkpoint hash does not match cached features')
  chk=hashlib.sha256((audit['pretrained_sha256']+'|'+''.join(r['sha256'] for r in manifest)+'|224net|224orig|transform_input=True').encode()).hexdigest()
  if audit.get('cache_fingerprint')!=chk:
   raise ValueError('The manifest SHA order differs from original cached patch feature extraction; aborting.')
 else:
  raise ValueError('Missing audit.json from the same Kaggle patch-feature extraction; do not compare unmatched data')
 whole=load_whole_features(args,manifest)
 cv=list(StratifiedGroupKFold(n_splits=5,shuffle=True,random_state=42).split(np.zeros(len(Y)),Y,GR))
 for fi,(tr,te) in enumerate(cv,start=1):
  if (set(GR[tr]) & set(GR[te])): raise RuntimeError('Similarity group leakage at fold '+str(fi))
  expected=np.array([int(r['fold']) for r in manifest])
  if not np.all(expected[te]==fi):raise RuntimeError('Fold assignment differs from manifest')
 pred={name:np.full(len(Y),-1,dtype=int) for name in ['pca16','pca32','pca64','pca128','no_pca']}
 if whole is not None:pred['whole_image_pca64']=np.full(len(Y),-1,dtype=int)
 seed_preds={seed:np.full(len(Y),-1,dtype=int) for seed in range(args.random_seeds)}
 selected_rows=[];fold_rows=[]
 for fi,(tr,te) in enumerate(cv,start=1):
  print('Fold',fi,'of 5 | dev',len(tr),'test',len(te),flush=True)
  a=np.asarray(Z[tr],dtype=np.float32);b=np.asarray(Z[te],dtype=np.float32)
  yt=Y[tr]
  for pcs in [16,32,64,128]:
   print('  fitting PCA',pcs,'from development patches only',flush=True)
   pca=PCA(n_components=pcs,svd_solver='randomized',random_state=2026)
   pca.fit(a.reshape(-1,1024))
   za=pca.transform(a.reshape(-1,1024)).reshape(len(tr),64,pcs).astype('float32')
   zb=pca.transform(b.reshape(-1,1024)).reshape(len(te),64,pcs).astype('float32')
   pred[f'pca{pcs}'][te]=svc_predict(za.reshape(len(tr),-1),zb.reshape(len(te),-1),yt)
   if pcs==64:
    for seed in range(args.random_seeds):
     chosen=sorted(np.random.default_rng(62026+fi+64+20+10000*seed).choice(64,20,replace=False).tolist())
     xtr=za[:,chosen,:].reshape(len(tr),-1);xte=zb[:,chosen,:].reshape(len(te),-1)
     seed_preds[seed][te]=svc_predict(xtr,xte,yt)
     selected_rows.append({'fold':fi,'seed_index':seed,'rng_seed':62026+fi+64+20+10000*seed,'positions_zero_based':json.dumps(chosen)})
   del za,zb,pca
  print('  no-PCA full 64 patches -> 65,536-d SVM',flush=True)
  pred['no_pca'][te]=svc_predict(a.reshape(len(tr),-1),b.reshape(len(te),-1),yt)
  del a,b
  if whole is not None:
   pca=PCA(n_components=64,svd_solver='randomized',random_state=2026)
   xa=pca.fit_transform(np.asarray(whole[tr]));xt=pca.transform(np.asarray(whole[te]))
   pred['whole_image_pca64'][te]=svc_predict(xa,xt,yt)
  fold_rows.append({'fold':fi,'train_images':len(tr),'test_images':len(te),'train_groups':len(set(GR[tr])),'test_groups':len(set(GR[te]))})
 # all analysis is from pooled out-of-fold predictions
 results=[]
 for name,p in pred.items():
  assert np.all(p>=0),name
  results.append({'model':name,'condition':'fixed group CV / exploratory','n':len(p),**metrics(Y,p)})
 rand_rows=[]
 for seed,p in seed_preds.items():
  assert np.all(p>=0)
  rand_rows.append({'seed_index':seed,**metrics(Y,p)})
 if rand_rows:
  for field in ['accuracy_pct','macro_f1_pct','benign_recall_pct']:
   vals=np.array([r[field] for r in rand_rows]);print(f'random20 {field}: {vals.mean():.3f}±{vals.std(ddof=1):.3f}',flush=True)
  results.append({'model':'random20_multiseed','condition':f'{args.random_seeds} random seeds on fixed group CV; mean ±sd across seeds','n':len(Y),
    **{k:float(np.mean([r[k] for r in rand_rows])) for k in metrics(Y,Y)}})
  results[-1]['macro_f1_sd_pct']=float(np.std([r['macro_f1_pct'] for r in rand_rows],ddof=1))
 def save(name,rows):
  if not rows:return
  keys=list(dict.fromkeys(k for row in rows for k in row));
  with (out/name).open('w',newline='',encoding='utf-8') as f:
   w=csv.DictWriter(f,fieldnames=keys);w.writeheader();w.writerows(rows)
 save('stage2_ablation_summary.csv',results)
 save('random20_multiseed_summary.csv',rand_rows)
 save('random20_selected_patch_positions.csv',selected_rows)
 save('stage2_fold_distribution.csv',fold_rows)
 oof=[]
 for i,r in enumerate(manifest):
  x={'index':i,'file':r['file'],'sha256':r['sha256'],'label_code':int(Y[i]),'group':int(GR[i]),'fold':r['fold']}
  for k,p in pred.items(): x['pred_'+k]=int(p[i])
  for seed,p in seed_preds.items():x[f'random20_seed{seed:02d}']=int(p[i])
  oof.append(x)
 save('stage2_oof_predictions.csv',oof)
 # Verify that the original 64-patch reference result is still reproduced (allow tiny numerical tolerance).
 reference=next(v for v in results if v['model']=='pca64')
 if abs(reference['accuracy_pct']-96.68)>0.05 or abs(reference['macro_f1_pct']-93.02)>0.05:
  print('WARNING: reconstructed 64-patch results differ from published reference; CHECK input and preprocessing.', reference, flush=True)
 (out/'stage2_run_info.json').write_text(json.dumps({'cache':str(root),'manifest':args.manifest,'n':len(Y),'folds':5,'random_seeds':args.random_seeds,'pca_dims':[16,32,64,128],'missing_test':'No nested CV run; selected-best-of-17 remains exploratory','full_image_available':whole is not None,'patient_disjoint':False},indent=2))
 print('New experiment results saved to',out,flush=True)

if __name__=='__main__':
 ap=argparse.ArgumentParser()
 ap.add_argument('--cache',required=True,help='Path containing features_64_224.npy, labels.npy, groups.npy, audit.json')
 ap.add_argument('--manifest',required=True,help='Path to image_manifest.csv')
 ap.add_argument('--dataset',help='Original IQ-OTH/NCCD images folder or ZIP for whole-image baseline')
 ap.add_argument('--weights',help='Official googlenet-1378be20.pth')
 ap.add_argument('--out',default='./GHDNN_stage2_results')
 ap.add_argument('--random-seeds',type=int,default=20)
 args=ap.parse_args()
 if args.random_seeds<2:raise ValueError('Use >=2 random seeds')
 evaluate(args)
